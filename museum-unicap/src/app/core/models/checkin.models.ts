/** Canonical visit types shared with the back-end contract. */
export type VisitType = 'individual' | 'familia' | 'escola' | 'academico';

/** Age ranges used for museum visitor statistics. */
export type AgeRange = 'crianca' | 'jovem' | 'adulto' | 'senior';

/** Relationship between the primary visitor and UNICAP. */
export type InstitutionalBond = 'comunidade' | 'aluno' | 'professor' | 'egresso';

/** Optional contact details and a separate, explicit communication consent. */
export interface CheckInContact {
  phone?: string;
  email?: string;
  communicationConsent: boolean;
}

/**
 * Payload for `POST /api/v1/checkins`.
 * The server is the authority for date/time and the generated protocol.
 */
export interface CheckInRequest {
  visitType: VisitType;
  /** Total number of people in the visit. Must be greater than zero. */
  visitorCount: number;
  visitorAgeRange: AgeRange;
  institutionalBond: InstitutionalBond;
  federationUnit: string;
  municipality: string;
  /** Only collected when the municipality is Recife (kiosk quick-select). */
  neighborhood: string | null;
  /** `null` when the visitor skips the optional contact step. */
  contact: CheckInContact | null;
  terminalId: string;
}

/** Response of `POST /api/v1/checkins`. */
export interface CheckInResponse {
  /** Unique protocol generated by the back end. */
  protocol: string;
  /** Server-side check-in timestamp (ISO 8601). */
  checkedInAt: string;
  /** Position of the visitor in the current day, when provided by the API. */
  visitorCountToday?: number;
}
